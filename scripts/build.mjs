// Builds the two generated modules the server imports (src/gen/), so the Pages Function bundles with no build step of its own:
//   src/gen/engine.js  Windline's one forecast engine, exactly as windline.tech serves it to every surface (engine-core.js,
//                      generated there from windlineEngine()). Never edited here: re-run this to pick up a newer engine.
//   src/gen/widget.js  the map widget (widget/widget.html) as a string, served as the ui:// resource.
//   node scripts/build.mjs            both (fetches the engine)
//   node scripts/build.mjs --widget   the widget only (offline)
//   node scripts/build.mjs --check    exit 1 if the engine here is older than windline.tech's
//   node scripts/build.mjs --engine   the engine only (livedot's site build runs this first; if windline.tech doesn't answer, the
//                                     copy already here is kept, and with none it fails, so a deploy never ships without it)
// The engine is Windline's and isn't part of this repository or its licence: src/gen/engine.js is gitignored and fetched here.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const GEN = path.join(ROOT, 'src', 'gen');
const ENGINE_URL = process.env.ENGINE_URL || 'https://windline.tech/engine-core.js';
const args = process.argv.slice(2);
fs.mkdirSync(GEN, { recursive: true });

const versionOf = (src) => (String(src).match(/WL_VERSION = '([0-9a-f]+)'/) || [])[1] || null;

async function engine() {
  const have = fs.existsSync(path.join(GEN, 'engine.js'));
  let r; try { r = await fetch(ENGINE_URL, { signal: AbortSignal.timeout(20000) }); } catch (e) { r = null; }
  if (!r || !r.ok) { if (have && !args.includes('--check')) { console.warn(`engine: ${ENGINE_URL} didn't answer; keeping the copy in src/gen/engine.js`); return; } throw new Error(`engine: ${ENGINE_URL} answered ${r ? r.status : 'nothing'}`); }
  const src = await r.text(), v = versionOf(src);
  if (!v || !/function windlineEngine\(\)/.test(src) || !/var WL = /.test(src)) throw new Error('engine: not the engine (no WL_VERSION / windlineEngine)');
  if (args.includes('--check')) {
    const here = fs.existsSync(path.join(GEN, 'engine.js')) ? versionOf(fs.readFileSync(path.join(GEN, 'engine.js'), 'utf8')) : null;
    if (here !== v) { console.error(`engine: here ${here}, windline.tech ${v}. Run node scripts/build.mjs`); process.exit(1); }
    console.log(`engine: ${v}, current`); return;
  }
  const out = `// GENERATED by scripts/build.mjs from ${ENGINE_URL} (WL_VERSION ${v}). Do not edit: the maths lives only in Windline's\n`
    + `// windlineEngine(), and every surface runs this same code. Re-run the build to take a newer engine.\n`
    + src.replace(/^\/\/ GENERATED.*\n/, '') + '\nexport { WL, WL_VERSION };\n';
  fs.writeFileSync(path.join(GEN, 'engine.js'), out);
  console.log(`src/gen/engine.js: WL_VERSION ${v}, ${out.length} bytes`);
}

function widget() {
  const html = fs.readFileSync(path.join(ROOT, 'widget', 'widget.html'), 'utf8');
  fs.writeFileSync(path.join(GEN, 'widget.js'), `// GENERATED by scripts/build.mjs from widget/widget.html. Edit the HTML, then re-run.\nexport const WIDGET_HTML = ${JSON.stringify(html)};\n`);
  console.log(`src/gen/widget.js: ${html.length} bytes`);
}

// The events event_weather knows by name beyond the apps' own races: livedot's published event previews (livedot.me/guides/
// <slug>/, type: preview, never a draft), from the LiveDot repo's content/guides when it's beside this folder. Each keeps what the
// preview page itself uses: the date, the start time, the pace the page is timed for, and the course line (thinned to 600 points).
// Run again when a preview is published; a draft never goes in.
function events() {
  const G = path.join(ROOT, '..', 'content', 'guides');
  if (!fs.existsSync(G)) { console.log('events: no content/guides beside mcp/ (the mirror): src/gen/events.js kept as it is'); return; }
  const thin = (pts, max) => { if (pts.length <= max) return pts.map((p) => [p[0], p[1]]); const k = (pts.length - 1) / (max - 1), o = []; for (let i = 0; i < max; i++) { const p = pts[Math.round(i * k)]; o.push([p[0], p[1]]); } return o; };
  const out = [];
  for (const f of fs.readdirSync(G).filter((x) => x.endsWith('.md'))) {
    const md = fs.readFileSync(path.join(G, f), 'utf8'), fm = (md.match(/^---\n([\s\S]*?)\n---/) || [])[1] || '';
    const get = (k) => ((fm.match(new RegExp('^' + k + ':\\s*(.+)$', 'm')) || [])[1] || '').replace(/^"|"$/g, '').trim();
    const slug = get('slug') || f.replace(/\.md$/, ''), file = path.join(G, 'data', slug + '.event.json');
    if (get('type') !== 'preview' || /^true$/.test(get('draft')) || !fs.existsSync(file)) continue;
    if (get('date') && get('date') > new Date().toISOString().slice(0, 10)) continue; // not out yet (staggered publish dates)
    const e = JSON.parse(fs.readFileSync(file, 'utf8')), name = (fm.match(/^event:\n\s+name:\s*(.+)$/m) || [])[1] || `${e.event} ${e.edition}`;
    const sport = /run/.test(e.sport) ? 'run' : 'ride';
    const days = e.stages ? e.stages.map((s) => ({ n: s.n, name: s.name, date: s.date, start: s.start, km: s.km, line: thin(s.line, 400) }))
      : [{ n: 1, name: e.event, date: e.date, start: e.start, km: e.km, line: thin(e.line, 600) }];
    out.push({ slug, name: name.trim(), event: e.event, edition: e.edition, sport, tz: e.tz, utcOffset: e.utcOffset, pace: e.pace, stops: e.stops || 0, timedFor: e.timedFor || null,
      url: `https://livedot.me/guides/${slug}/`, days });
  }
  fs.writeFileSync(path.join(GEN, 'events.js'), `// GENERATED by scripts/build.mjs from livedot's published event previews (content/guides, never a draft). Re-run when one is published.\nexport const EVENTS = ${JSON.stringify(out)};\n`);
  console.log(`src/gen/events.js: ${out.length} published previews (${out.map((x) => x.slug).join(', ')})`);
}

(async () => {
  if (!args.includes('--widget')) await engine();
  if (args.includes('--engine')) return;
  if (!args.includes('--check')) { widget(); if (!args.includes('--widget')) events(); }
})().catch((e) => { console.error(e.message); process.exit(1); });
